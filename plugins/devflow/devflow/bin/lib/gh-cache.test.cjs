const { test, describe } = require('node:test');
const assert = require('node:assert');

const cache = require('./gh-cache.cjs');
const ghTrd = require('./gh-trd.cjs');
const ghBody = require('./gh-body.cjs');
const ghWiki = require('./gh-wiki.cjs');
const ghMapping = require('./gh-mapping.cjs');
const { STORE_FIXTURE } = require('./__fixtures__/gh-store-fixtures.cjs');

const F = STORE_FIXTURE;
const DIR = F.objectiveDir;
const SUMMARY_FILE = F.summaryFile;
const VERIFICATION_FILE = '07-VERIFICATION.md';
const VERIFICATION_TEXT = '# Objective 7 verification\n\nAll success criteria met.\n';
const CRLF = (s) => s.replace(/\n/g, '\r\n');

// ─── Model builders (hand-built; no gh, no fs) ───────────────────────────────

const wikiSection = (dir) => ghBody.buildWikiSection({
  dir,
  page: ghWiki.objectivePage(dir),
  url: `https://github.com/o/r/wiki/${ghWiki.objectivePage(dir)}/abc1234`,
  sha: 'abc1234',
});

/** The body of an objective issue: id marker, then the managed wiki section carrying the directory name. */
const objectiveBody = (id, dir) => `<!-- devflow:id=${id} -->\n<!-- devflow:begin wiki -->\n${wikiSection(dir)}\n<!-- devflow:end wiki -->\n`;

/** The comments of a file comment (`summary` / `verification`), split into numbered parts when `max` is given. */
function fileComment(id, kind, file, text, { max = 60000, firstId = 5000, updatedAt = '2026-01-01T00:00:10Z' } = {}) {
  const marker = ghBody.commentMarker(id, kind);
  const payload = `${ghTrd.fileLine(file)}\n${text}`;
  const parts = ghTrd.splitParts(payload, max, { reserve: marker.length + 1 });
  return parts.map((part, i) => ({ id: firstId + i, body: `${marker}\n${part}`, updated_at: updatedAt }));
}

function trdIssue(number, file, { state = 'open', comments = [], crlf = false } = {}) {
  const id = ghMapping.toTrdId(file.slice(0, 5));
  const body = ghTrd.encodeTrdBody({ id, file, text: F.trds[file] });
  return {
    id, number, rest_id: 1_000_000 + number, title: `[TRD ${file.slice(0, 5)}] ${file}`, state,
    body: crlf ? CRLF(body) : body, updated_at: '2026-01-01T00:00:05Z', comments,
  };
}

function makeModel(overrides = {}) {
  const pages = {
    Project: F.project,
    Requirements: CRLF(F.requirements),
    'Codebase-Stack': '# Stack\n\nNode.\n',
    'Codebase-Conventions': '# Conventions\n\nNo semicolon wars.\n',
    'Objective-7-store-demo': F.objective,
    'Objective-7-store-demo-Context': F.context,
    'Objective-7-store-demo-Research': F.research,
    Roadmap: 'a hand written wiki roadmap that must never be materialised\n',
    Home: '# Home\n',
  };
  return {
    ok: true,
    repo: 'o/r',
    pages,
    pages_report: { mode: 'wiki', skipped: false },
    objectives: [{
      id: '7', number: 41, rest_id: 1_000_041, title: '[Objective 7] Store demo', name: 'Store demo', state: 'open',
      milestone: 'v9.9 Store Demo', body: objectiveBody('7', DIR), updated_at: '2026-01-01T00:00:01Z',
      comments: fileComment('7', 'verification', VERIFICATION_FILE, VERIFICATION_TEXT, { firstId: 7000 }),
    }],
    trds: [
      trdIssue(42, F.trdFiles[0], { state: 'closed', comments: fileComment('7-01', 'summary', SUMMARY_FILE, F.summary) }),
      trdIssue(43, F.trdFiles[1], { crlf: true }),
      trdIssue(44, F.trdFiles[2]),
    ],
    decisions: [],
    ...overrides,
  };
}

const EXPECTED_ROADMAP = [
  '<!-- generated by devflow; do not edit -->',
  '# Roadmap',
  '',
  '## v9.9 Store Demo',
  '',
  '### Objective 7: Store demo  (#41, open)',
  'TRDs:',
  '- [x] 07-01 alpha (wave 1, #42)',
  '- [ ] 07-02 beta (wave 1, #43)',
  '- [ ] 07-03 gamma (wave 2, #44, blocked by 07-01)',
  '',
].join('\n');

const objectiveStub = (id, name, milestone = 'v9.9 Store Demo') => ({
  id, number: 100 + Math.round(parseFloat(id) * 10), rest_id: 1, title: `[Objective ${id}] ${name}`, name, state: 'open',
  milestone, body: objectiveBody(id, `${String(Math.trunc(parseFloat(id))).padStart(2, '0')}-${name.toLowerCase()}`), updated_at: null, comments: [],
});

// ═══ Task 1: materialisation and renderers ═══════════════════════════════════

describe('materialize', () => {
  test('1: lays out the canonical tree from a remote model', () => {
    const { files, rejected } = cache.materialize(makeModel());
    assert.deepStrictEqual(rejected, []);
    assert.deepStrictEqual(Object.keys(files).sort(), [
      'PROJECT.md',
      'REQUIREMENTS.md',
      'codebase/CONVENTIONS.md',
      'codebase/STACK.md',
      `objectives/${DIR}/07-01-alpha-TRD.md`,
      `objectives/${DIR}/07-01-alpha-SUMMARY.md`,
      `objectives/${DIR}/07-02-beta-TRD.md`,
      `objectives/${DIR}/07-03-gamma-TRD.md`,
      `objectives/${DIR}/07-CONTEXT.md`,
      `objectives/${DIR}/07-RESEARCH.md`,
      `objectives/${DIR}/07-VERIFICATION.md`,
      `objectives/${DIR}/OBJECTIVE.md`,
    ].sort());
    assert.ok(Object.keys(files).length >= 10);

    assert.strictEqual(files['PROJECT.md'], F.project);
    assert.strictEqual(files[`objectives/${DIR}/OBJECTIVE.md`], F.objective);
    assert.strictEqual(files[`objectives/${DIR}/07-CONTEXT.md`], F.context);
    assert.strictEqual(files[`objectives/${DIR}/07-RESEARCH.md`], F.research);
    assert.strictEqual(files[`objectives/${DIR}/07-01-alpha-TRD.md`], F.trds['07-01-alpha-TRD.md']);
    assert.strictEqual(files[`objectives/${DIR}/07-01-alpha-SUMMARY.md`], F.summary);
    assert.strictEqual(files[`objectives/${DIR}/07-VERIFICATION.md`], VERIFICATION_TEXT);
  });

  test('1: the generated Roadmap page is never materialised, and an unmapped page is reported', () => {
    const r = cache.materialize(makeModel());
    assert.ok(!('ROADMAP.md' in r.files));
    assert.deepStrictEqual(r.unmapped_pages, ['Home']);
  });

  test('1: CRLF from GitHub is normalised in pages and TRD bodies, and text is never trimmed', () => {
    const { files } = cache.materialize(makeModel());
    assert.strictEqual(files['REQUIREMENTS.md'], F.requirements, 'CRLF page normalised');
    const beta = files[`objectives/${DIR}/07-02-beta-TRD.md`];
    assert.strictEqual(beta, F.trds['07-02-beta-TRD.md'], 'CRLF TRD body normalised');
    assert.ok(!beta.includes('\r'));
    const gamma = files[`objectives/${DIR}/07-03-gamma-TRD.md`];
    assert.strictEqual(gamma, F.trds['07-03-gamma-TRD.md']);
    assert.ok(!gamma.endsWith('\n'), 'a TRD without a trailing newline stays without one');
  });

  test('1: a multi-part SUMMARY comment is rejoined byte-exactly', () => {
    const comments = fileComment('7-01', 'summary', SUMMARY_FILE, F.summary, { max: 220 });
    assert.ok(comments.length > 1, 'the fixture summary must split');
    const model = makeModel();
    model.trds[0] = trdIssue(42, F.trdFiles[0], { state: 'closed', comments: [...comments].reverse() });
    const { files } = cache.materialize(model);
    assert.strictEqual(files[`objectives/${DIR}/07-01-alpha-SUMMARY.md`], F.summary);
  });

  test('1: materialize is pure and deterministic', () => {
    const model = makeModel();
    const before = JSON.stringify(model);
    const a = cache.materialize(model);
    const b = cache.materialize(model);
    assert.deepStrictEqual(a, b);
    assert.strictEqual(JSON.stringify(model), before, 'the model is not mutated');
  });

  test('1: files that come from issues and comments are mapped to their outbox base keys', () => {
    const { sources } = cache.materialize(makeModel());
    assert.strictEqual(sources[`objectives/${DIR}/07-01-alpha-TRD.md`], '7-01');
    assert.strictEqual(sources[`objectives/${DIR}/07-01-alpha-SUMMARY.md`], '7-01#summary');
    assert.strictEqual(sources[`objectives/${DIR}/07-VERIFICATION.md`], '7#verification');
    assert.ok(!('PROJECT.md' in sources), 'a wiki page has no issue base');
  });

  test('2: a TRD whose devflow:file would leave the objective directory is rejected', () => {
    const model = makeModel();
    model.trds.push({
      id: '7-04', number: 45, rest_id: 1_000_045, title: 'evil', state: 'open', updated_at: null, comments: [],
      body: '<!-- devflow:id=7-04 -->\n<!-- devflow:file=../../x -->\nowned\n',
    });
    const r = cache.materialize(model);
    assert.ok(!Object.keys(r.files).some((p) => p.includes('..')));
    assert.strictEqual(r.rejected.length, 1);
    assert.match(r.rejected[0].reason, /not a devflow TRD body/);
    assert.strictEqual(r.rejected[0].number, 45);
  });

  test('2: a TRD file that does not start with its own id prefix is rejected', () => {
    const model = makeModel();
    model.trds.push({
      id: '7-04', number: 45, rest_id: 1_000_045, title: 'wrong prefix', state: 'open', updated_at: null, comments: [],
      body: ghTrd.encodeTrdBody({ id: '7-04', file: '09-01-other-TRD.md', text: 'stolen\n' }),
    });
    const r = cache.materialize(model);
    assert.ok(!Object.keys(r.files).some((p) => p.endsWith('09-01-other-TRD.md')));
    assert.strictEqual(r.rejected.length, 1);
    assert.match(r.rejected[0].reason, /07-04|7-04/);
  });

  test('2: a SUMMARY comment named for another TRD is rejected, not written', () => {
    const model = makeModel();
    model.trds[1].comments = fileComment('7-02', 'summary', '07-09-intruder-SUMMARY.md', 'x\n', { firstId: 6000 });
    const r = cache.materialize(model);
    assert.ok(!Object.keys(r.files).some((p) => p.includes('intruder')));
    assert.strictEqual(r.rejected.length, 1);
    assert.strictEqual(r.rejected[0].kind, 'summary');
  });

  test('2: a devflow:dir that does not belong to its objective rejects the objective directory', () => {
    const model = makeModel();
    model.objectives[0].body = objectiveBody('7', '09-someone-else');
    const r = cache.materialize(model);
    assert.ok(!Object.keys(r.files).some((p) => p.startsWith('objectives/')));
    assert.strictEqual(r.rejected[0].kind, 'dir');
    assert.deepStrictEqual(r.orphan_trds.map((o) => o.id), ['7-01', '7-02', '7-03']);
  });

  test('2: two sources for one path never overwrite each other', () => {
    const model = makeModel();
    model.trds.push(trdIssue(46, F.trdFiles[0], {}));
    const r = cache.materialize(model);
    assert.strictEqual(r.rejected.length, 1);
    assert.match(r.rejected[0].reason, /already provided|collides/);
    assert.strictEqual(r.files[`objectives/${DIR}/07-01-alpha-TRD.md`], F.trds['07-01-alpha-TRD.md']);
  });
});

describe('renderRoadmap', () => {
  test('3: matches the expected literal string for the fixture model', () => {
    assert.strictEqual(cache.renderRoadmap(makeModel()), EXPECTED_ROADMAP);
  });

  test('3: begins with the generated header', () => {
    assert.ok(cache.renderRoadmap(makeModel()).startsWith(`${cache.GENERATED_HEADER}\n`));
    assert.strictEqual(cache.GENERATED_HEADER, '<!-- generated by devflow; do not edit -->');
  });

  test('3: objectives sort numerically (2, 2.1, 10), not as text', () => {
    const model = makeModel({ trds: [], objectives: [
      objectiveStub('10', 'ten'), objectiveStub('2.1', 'two-one'), objectiveStub('2', 'two'),
    ] });
    const headings = cache.renderRoadmap(model).split('\n').filter((l) => l.startsWith('### '));
    assert.deepStrictEqual(headings.map((h) => h.split(':')[0]), ['### Objective 2', '### Objective 2.1', '### Objective 10']);
  });

  test('3: objectives group by milestone, naturally ordered, with no-milestone last', () => {
    const model = makeModel({ trds: [], objectives: [
      objectiveStub('3', 'late', 'v10.0 Later'), objectiveStub('4', 'floating', null), objectiveStub('2', 'early', 'v9.9 Store Demo'),
    ] });
    const text = cache.renderRoadmap(model);
    const order = text.split('\n').filter((l) => l.startsWith('## '));
    assert.deepStrictEqual(order, ['## v9.9 Store Demo', '## v10.0 Later', '## Unscheduled']);
  });

  test('3: output is deterministic and carries no timestamps', () => {
    const model = makeModel();
    assert.strictEqual(cache.renderRoadmap(model), cache.renderRoadmap(JSON.parse(JSON.stringify(model))));
    assert.doesNotMatch(cache.renderRoadmap(model), /\d{4}-\d{2}-\d{2}T/);
  });

  test('3: a failed read refuses to render', () => {
    assert.throws(() => cache.renderRoadmap({ ok: false, error: 'boom' }), /boom/);
  });
});

describe('renderState', () => {
  test('4: starts with the header, names objective 7 current and counts closed TRDs', () => {
    const text = cache.renderState(makeModel());
    assert.ok(text.startsWith(`${cache.GENERATED_HEADER}\n`));
    assert.match(text, /Objective 7: Store demo/);
    assert.match(text, /Current Position[\s\S]*Objective 7: Store demo/);
    assert.match(text, /1\/3 TRDs done/);
  });

  test('4: the current objective is the lowest-numbered OPEN one', () => {
    const closed = { ...objectiveStub('2', 'done'), state: 'closed' };
    const model = makeModel({ trds: [], objectives: [objectiveStub('10', 'ten'), closed, objectiveStub('3', 'three')] });
    const text = cache.renderState(model);
    const position = text.split('## Objectives')[0];
    assert.match(position, /Objective 3: three/);
    assert.doesNotMatch(position, /Objective 2:/);
  });

  test('4: no open objective says so', () => {
    const model = makeModel({ trds: [], objectives: [{ ...objectiveStub('2', 'done'), state: 'closed' }] });
    assert.match(cache.renderState(model), /No open objectives/);
  });

  test('4: no objectives at all still renders a generated file', () => {
    const text = cache.renderState(makeModel({ objectives: [], trds: [] }));
    assert.ok(text.startsWith(cache.GENERATED_HEADER));
    assert.match(text, /No open objectives/);
  });
});

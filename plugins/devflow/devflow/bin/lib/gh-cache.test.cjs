const wikiSection = (dir) => ghBody.buildWikiSection({
  dir,
  page: ghWiki.objectivePage(dir),
  url: `https://github.com/o/r/wiki/${ghWiki.objectivePage(dir)}/abc1234`,
  sha: 'abc1234',
});

/** The body of an objective issue: id marker, then the managed wiki section carrying the directory name. */
const objectiveBody = (id, dir) => `<!-- devflow:id=${id} -->\n<!-- devflow:begin wiki -->\n${wikiSection(dir)}\n<!-- devflow:end wiki -->\n`;

/** The comments of a file comment (`summary` / `verification`), split into numbered parts when `max` is given. */
function fileComment(id, kind, file, text, { max = 60000, firstId = 5000, updatedAt = '2026-01-01T00:00:10Z' } = {}) {
  const marker = ghBody.commentMarker(id, kind);
  const payload = `${ghTrd.fileLine(file)}\n${text}`;
  const parts = ghTrd.splitParts(payload, max, { reserve: marker.length + 1 });
  return parts.map((part, i) => ({ id: firstId + i, body: `${marker}\n${part}`, updated_at: updatedAt }));
}

function trdIssue(number, file, { state = 'open', comments = [], crlf = false } = {}) {
  const id = ghMapping.toTrdId(file.slice(0, 5));
  const body = ghTrd.encodeTrdBody({ id, file, text: F.trds[file] });
  return {
    id, number, rest_id: 1_000_000 + number, title: `[TRD ${file.slice(0, 5)}] ${file}`, state,
    body: crlf ? CRLF(body) : body, updated_at: '2026-01-01T00:00:05Z', comments,
  };
}

function makeModel(overrides = {}) {
  const pages = {
    Project: F.project,
    Requirements: CRLF(F.requirements),
    'Codebase-Stack': '# Stack\n\nNode.\n',
    'Codebase-Conventions': '# Conventions\n\nNo semicolon wars.\n',
    'Objective-7-store-demo': F.objective,
    'Objective-7-store-demo-Context': F.context,
    'Objective-7-store-demo-Research': F.research,
    Roadmap: 'a hand written wiki roadmap that must never be materialised\n',
    Home: '# Home\n',
  };
  return {
    ok: true,
    repo: 'o/r',
    pages,
    pages_report: { mode: 'wiki', skipped: false },
    objectives: [{
      id: '7', number: 41, rest_id: 1_000_041, title: '[Objective 7] Store demo', name: 'Store demo', state: 'open',
      milestone: 'v9.9 Store Demo', body: objectiveBody('7', DIR), updated_at: '2026-01-01T00:00:01Z',
      comments: fileComment('7', 'verification', VERIFICATION_FILE, VERIFICATION_TEXT, { firstId: 7000 }),
    }],
    trds: [
      trdIssue(42, F.trdFiles[0], { state: 'closed', comments: fileComment('7-01', 'summary', SUMMARY_FILE, F.summary) }),
      trdIssue(43, F.trdFiles[1], { crlf: true }),
      trdIssue(44, F.trdFiles[2]),
    ],
    decisions: [],
    ...overrides,
  };
}


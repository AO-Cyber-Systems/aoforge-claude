    assert.deepStrictEqual(model.trds.map((t) => [t.id, t.number, t.state]), [['7-01', ALPHA, 'closed'], ['7-02', BETA, 'open'], ['7-03', GAMMA, 'open']]);
    assert.strictEqual(model.decisions.length, 1);

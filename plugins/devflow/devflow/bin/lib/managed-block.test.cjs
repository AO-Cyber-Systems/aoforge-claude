'use strict';

// Test list (TDD Playbook habit #2 — reviewable artifact, written before implementation).
// TRD 36-02 Task 1: the versioned DEVFLOW:START/END managed block.
//
//   1. read('no markers here') → null.
//   2. Legacy start marker (exact string from templates/claude-md.md:14) + END →
//      meta = {v:null, src:null, legacy:true}; content is the text between the markers minus one
//      leading and one trailing newline.
//   3. `<!-- DEVFLOW:START v=2 src=claude-md -->` → meta = {v:'2', src:'claude-md', legacy:false}.
//   4. Attribute order and spacing tolerated: `<!--DEVFLOW:START src=x v=1-->` parses.
//   5. render('body', {v:'2', src:'claude-md'}) →
//      '<!-- DEVFLOW:START v=2 src=claude-md -->\nbody\n<!-- DEVFLOW:END -->'
//      (trailing newlines in content collapsed).
//   6. Replace: pre + legacyBlock + post → output starts with pre and ends with post byte-for-byte;
//      the new block is versioned.
//   7. CRLF: pre/post using \r\n are preserved exactly.
//   8. Append to text without a block: 'a\n' → 'a\n\n' + block + '\n'; 'a' → 'a\n\n' + block + '\n';
//      '' → block + '\n'.
//   9. position: 'prepend' → block + '\n\n' + text.
//  10. Idempotent: upsert(upsert(t, c, m), c, m) === upsert(t, c, m).
//  11. Two blocks → read throws ManagedBlockError with message containing 'multiple'.
//  12. START without END → throws ManagedBlockError containing 'unterminated'; END alone → null.
//  13. isStale: legacy → true; v='1' vs '2' → true; '2' vs '2' → false; '10' vs '9' → false;
//      '1.2' vs '1.10' → true.
//  14. upsert on text whose block is malformed rethrows (never writes a second block).

const { describe, test } = require('node:test');
const assert = require('node:assert/strict');

const mb = require('./managed-block.cjs');

// Exact legacy marker written by templates/claude-md.md:14 and map-codebase today.
const LEGACY_START =
  '<!-- DEVFLOW:START - Auto-generated by /devflow:map-codebase. Edit between these markers will be overwritten. -->';
const END = '<!-- DEVFLOW:END -->';
const META = { v: '2', src: 'claude-md' };
const V2_START = '<!-- DEVFLOW:START v=2 src=claude-md -->';

describe('managed-block read()', () => {
  test('1. text with no markers → null', () => {
    assert.equal(mb.read('no markers here'), null);
    assert.equal(mb.read(''), null);
  });

  test('2. legacy unversioned marker parses as legacy; content strips one newline each side', () => {
    const pre = '# Project\n\n';
    const block = `${LEGACY_START}\n\n## Stack\n- Go\n\n${END}`;
    const text = `${pre}${block}\ntrailer\n`;
    const got = mb.read(text);
    assert.deepEqual(got.meta, { v: null, src: null, legacy: true });
    assert.equal(got.content, '\n## Stack\n- Go\n');
    assert.equal(got.start, pre.length);
    assert.equal(got.end, pre.length + block.length);
    assert.equal(text.slice(got.start, got.end), block);
  });

  test('3. versioned marker parses v and src', () => {
    const got = mb.read(`${V2_START}\nbody\n${END}\n`);
    assert.deepEqual(got.meta, { v: '2', src: 'claude-md', legacy: false });
    assert.equal(got.content, 'body');
  });

  test('4. attribute order and spacing are tolerated', () => {
    const got = mb.read('x\n<!--DEVFLOW:START src=x v=1-->\nbody\n<!--DEVFLOW:END-->\n');
    assert.deepEqual(got.meta, { v: '1', src: 'x', legacy: false });
    assert.equal(got.content, 'body');
    assert.deepEqual(mb.parseStartMarker('<!--   DEVFLOW:START   v=1.4.0   src=y   -->'), {
      v: '1.4.0', src: 'y', legacy: false,
    });
    assert.equal(mb.parseStartMarker('<!-- not a devflow marker -->'), null);
  });

  test('2b. CRLF content strips exactly one \\r\\n each side', () => {
    const got = mb.read(`${V2_START}\r\nline1\r\nline2\r\n${END}`);
    assert.equal(got.content, 'line1\r\nline2');
  });
});

describe('managed-block render()', () => {
  test('5. render emits the versioned marker; trailing newlines in content collapse', () => {
    const expected = `${V2_START}\nbody\n${END}`;
    assert.equal(mb.render('body', META), expected);
    assert.equal(mb.render('body\n\n\n', META), expected);
    assert.equal(mb.render('body\r\n', META), expected);
  });

  test('5b. render → read round-trips content and meta', () => {
    const content = '\n## Stack\n\n- Go';
    const got = mb.read(mb.render(content, META));
    assert.equal(got.content, content);
    assert.deepEqual(got.meta, { v: '2', src: 'claude-md', legacy: false });
  });
});

describe('managed-block upsert()', () => {
  test('6. replacing a legacy block preserves pre and post byte-for-byte', () => {
    const pre = '# My project\n\nHand-written notes, keep me.\n\n';
    const post = '\n\n## Mine\n\nAlso keep me.   \n\t\n';
    const text = `${pre}${LEGACY_START}\nold generated stuff\n${END}${post}`;
    const out = mb.upsert(text, 'new body', META);
    assert.ok(out.startsWith(pre));
    assert.ok(out.endsWith(post));
    assert.equal(out, `${pre}${mb.render('new body', META)}${post}`);
    const got = mb.read(out);
    assert.equal(got.meta.legacy, false);
    assert.equal(got.meta.v, '2');
    assert.equal(got.content, 'new body');
  });

  test('7. CRLF outside the block is preserved exactly', () => {
    const pre = '# Title\r\n\r\nintro line\r\n\r\n';
    const post = '\r\n\r\n## After\r\ntext\r\n';
    const text = `${pre}${LEGACY_START}\r\nold\r\n${END}${post}`;
    const out = mb.upsert(text, 'fresh', META);
    assert.equal(out.slice(0, pre.length), pre);
    assert.equal(out.slice(out.length - post.length), post);
    assert.equal(out, `${pre}${mb.render('fresh', META)}${post}`);
  });

  test('8. appending when there is no block uses a single blank-line separator', () => {
    const block = mb.render('c', META);
    assert.equal(mb.upsert('a\n', 'c', META), `a\n\n${block}\n`);
    assert.equal(mb.upsert('a', 'c', META), `a\n\n${block}\n`);
    assert.equal(mb.upsert('', 'c', META), `${block}\n`);
  });

  test('9. position: prepend puts the block first', () => {
    const block = mb.render('c', META);
    assert.equal(mb.upsert('a\nb\n', 'c', META, { position: 'prepend' }), `${block}\n\na\nb\n`);
  });

  test('10. upsert is idempotent (append, replace, and prepend paths)', () => {
    const inputs = [
      '',
      'a',
      'a\n',
      `pre\n${LEGACY_START}\nold\n${END}\npost\n`,
      `pre\r\n${V2_START}\r\nold\r\n${END}\r\npost\r\n`,
    ];
    for (const t of inputs) {
      const once = mb.upsert(t, 'body\nline 2\n', META);
      assert.equal(mb.upsert(once, 'body\nline 2\n', META), once, `input ${JSON.stringify(t)}`);
    }
    const p = mb.upsert('x\n', 'c', META, { position: 'prepend' });
    assert.equal(mb.upsert(p, 'c', META, { position: 'prepend' }), p);
  });

  test('14. upsert on a malformed block rethrows and never writes a second block', () => {
    const two = `${V2_START}\na\n${END}\n\n${V2_START}\nb\n${END}\n`;
    assert.throws(() => mb.upsert(two, 'c', META), mb.ManagedBlockError);
    const open = `pre\n${LEGACY_START}\nno end here\n`;
    assert.throws(() => mb.upsert(open, 'c', META), mb.ManagedBlockError);
  });
});

describe('managed-block malformed input', () => {
  test('11. two blocks → ManagedBlockError mentioning multiple', () => {
    const text = `${LEGACY_START}\na\n${END}\n\n${V2_START}\nb\n${END}\n`;
    assert.throws(() => mb.read(text), (err) => {
      assert.ok(err instanceof mb.ManagedBlockError);
      assert.ok(err instanceof Error);
      assert.match(err.message, /multiple/);
      return true;
    });
  });

  test('12. START without END → unterminated; END alone → null; END before START does not close', () => {
    assert.throws(() => mb.read(`x\n${V2_START}\nbody\n`), (err) => {
      assert.ok(err instanceof mb.ManagedBlockError);
      assert.match(err.message, /unterminated/);
      return true;
    });
    assert.equal(mb.read(`x\n${END}\ny\n`), null);
    assert.throws(() => mb.read(`${END}\n${V2_START}\nbody\n`), /unterminated/);
  });
});

describe('managed-block isStale() / compareVersions()', () => {
  const block = (v) => mb.read(mb.render('x', { v, src: 's' }));

  test('13. staleness: legacy stale; lower v stale; equal/higher not; numeric dotted compare', () => {
    assert.equal(mb.isStale(mb.read(`${LEGACY_START}\nx\n${END}`), '1'), true);
    assert.equal(mb.isStale(block('1'), '2'), true);
    assert.equal(mb.isStale(block('2'), '2'), false);
    assert.equal(mb.isStale(block('10'), '9'), false);
    assert.equal(mb.isStale(block('1.2'), '1.10'), true);
    assert.equal(mb.isStale(block('3'), '2'), false);
  });

  test('13b. isStale accepts raw text and treats "no block" as not stale', () => {
    assert.equal(mb.isStale(null, '2'), false);
    assert.equal(mb.isStale('no block at all', '2'), false);
    assert.equal(mb.isStale(`a\n${mb.render('x', { v: '1', src: 's' })}\n`, '2'), true);
    assert.equal(mb.isStale(`a\n${LEGACY_START}\nx\n${END}\n`, '1'), true);
  });

  test('13c. compareVersions: split on dots, numeric, missing parts are 0', () => {
    assert.equal(mb.compareVersions('10', '9'), 1);
    assert.equal(mb.compareVersions('1.2', '1.10'), -1);
    assert.equal(mb.compareVersions('2', '2.0.0'), 0);
    assert.equal(mb.compareVersions('1.0.1', '1'), 1);
  });
});

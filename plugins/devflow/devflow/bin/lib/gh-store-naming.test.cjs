'use strict';

// gh-store-naming.test.cjs (TRD 55-04) — what a new store-mode objective issue is CALLED and what its footer SAYS.
// Item 55-6 of the live smoke: `objective add "Hello CLI"` made the issue `[Objective 1] 01-hello-cli` (the directory
// name, because a fresh store has no ROADMAP entry to read the name from), and the managed body ended with
// "Source of truth: `.planning/objectives/<dir>/` in this repo", which is wrong when the issue IS the record.
//
// Test list (TRD 55-04), outermost first:
//   title   1  store `objective add "Hello CLI"` on a project with an empty ROADMAP -> `[Objective 1] Hello CLI`
//           2  a ROADMAP entry names the objective -> that name is the title (the ROADMAP still wins)
//           3  no ROADMAP entry and no `# ` heading in OBJECTIVE.md -> the bare slug `hello-cli`, never `01-hello-cli`
//   footer  4  the created objective issue body ends with the store footer: "source of truth" and "cache", never
//              "in this repo"                                   (gh-body.test.cjs pins the builder, gh-sync.test.cjs
//                                                                the unchanged mirror text)
//
// Hermetic: hermeticEnv() temp HOME / outbox / cache dirs, the stateful fake GitHub through the gh-client seam, a fake
// clock, the wiki is a local bare repo over file://. No real GitHub, no network, no port, never ~/.claude.

const { describe, test, beforeEach, afterEach, mock } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const verbs = require('./planning-verbs.cjs');
const gh = require('./gh.cjs');
const client = require('./gh-client.cjs');
const objectiveLib = require('./objective.cjs');
const { createFakeGitHub } = require('./__fixtures__/gh-fake.cjs');
const { makeStoreProject, hermeticEnv } = require('./__fixtures__/gh-store-fixtures.cjs');
const { createWikiRemote, gitAvailable, applyGitTestEnv } = require('./__fixtures__/wiki-remote.cjs');

const T0 = Date.UTC(2026, 9, 1, 12, 0, 0);
const GENERATED_ROADMAP = '<!-- generated by devflow; do not edit -->\n# Roadmap\n';

// ─── Harness ─────────────────────────────────────────────────────────────────

let S;

/**
 * Hermetic env + a store project that starts EMPTY like the smoke's: the fixture's objective 7 is removed and the
 * ROADMAP is a generated view with no objective entry. `roadmap` replaces that ROADMAP text.
 */
function useEmptyStoreProject({ roadmap = GENERATED_ROADMAP } = {}) {
  beforeEach((t) => {
    const envh = hermeticEnv();
    const project = makeStoreProject({ store: true });
    fs.rmSync(path.join(project.root, '.planning', 'objectives', project.objectiveDir), { recursive: true, force: true });
    fs.mkdirSync(path.join(project.root, '.planning', 'objectives'), { recursive: true });
    fs.writeFileSync(path.join(project.root, '.planning', 'ROADMAP.md'), roadmap);
    const fake = createFakeGitHub(project.fakeOptions);
    const clock = { t: T0 };
    client._resetClient();
    client._setNow(() => clock.t);
    client._setSleep((ms) => { clock.t += ms; });
    gh._setRunGh(fake.runGh);
    gh._resetCache();

    const savedRemote = process.env.DEVFLOW_WIKI_REMOTE;
    let restoreGit = () => {};
    let remote = null;
    if (gitAvailable()) {
      restoreGit = applyGitTestEnv(path.join(envh.root, 'home'));
      remote = createWikiRemote();
      process.env.DEVFLOW_WIKI_REMOTE = remote.remoteUrl;
    }
    S = { envh, project, root: project.root, fake, clock, remote, restoreGit, savedRemote, skipped: false };
    if (!gitAvailable()) {
      S.skipped = true;
      t.skip('git is not available: store-mode verbs push wiki pages');
    }
  });
  afterEach(() => {
    client._resetClient();
    if (S.remote) S.remote.cleanup();
    S.restoreGit();
    if (S.savedRemote === undefined) delete process.env.DEVFLOW_WIKI_REMOTE;
    else process.env.DEVFLOW_WIKI_REMOTE = S.savedRemote;
    S.envh.restore();
    S.project.cleanup();
  });
}

class ExitSignal extends Error {
  constructor(code) {
    super(`process.exit(${code})`);
    this.code = code;
  }
}

/**
 * Run the real `objective add` command in-process (objective.cjs store branch -> planning-verbs.objectivePut ->
 * gh.syncObjective). The command ends in process.exit and prints JSON, so both are captured for the call.
 */
function runObjectiveAdd(description) {
  const written = [];
  const stdout = mock.method(process.stdout, 'write', (chunk) => { written.push(String(chunk)); return true; });
  const exit = mock.method(process, 'exit', (code) => { throw new ExitSignal(code); });
  let code = null;
  try {
    objectiveLib.cmdObjectiveAdd(S.root, description, false);
  } catch (e) {
    if (!(e instanceof ExitSignal)) throw e;
    code = e.code;
  } finally {
    stdout.mock.restore();
    exit.mock.restore();
  }
  return { code, out: JSON.parse(written.join('')) };
}

/** Write an OBJECTIVE.md for directory `dir` through the real store verb (the dir is created first, as `add` does). */
function putObjective(dir, id, text) {
  fs.mkdirSync(path.join(S.root, '.planning', 'objectives', dir), { recursive: true });
  const r = verbs.objectivePut(S.root, { id: String(id), text });
  assert.equal(r.ok, true, JSON.stringify(r));
  return r;
}

const objectiveIssues = () => S.fake.issues.filter((i) => !i.pr && /^\[Objective /.test(i.title));

// ─── Title ───────────────────────────────────────────────────────────────────

describe('55-04 store objective issue title', () => {
  useEmptyStoreProject();

  test('1. objective add "Hello CLI" on an empty ROADMAP -> the issue is titled `[Objective 1] Hello CLI`', () => {
    if (S.skipped) return;
    const { code, out } = runObjectiveAdd('Hello CLI');
    assert.equal(code, 0, JSON.stringify(out));
    assert.equal(out.objective_number, 1);
    assert.equal(out.directory, '.planning/objectives/01-hello-cli');
    const issues = objectiveIssues();
    assert.equal(issues.length, 1, `one objective issue, got ${JSON.stringify(issues.map((i) => i.title))}`);
    assert.equal(issues[0].title, '[Objective 1] Hello CLI');
  });

  test('3. no ROADMAP entry and no `# ` heading in OBJECTIVE.md -> the bare slug, never the numbered directory name', () => {
    if (S.skipped) return;
    putObjective('01-hello-cli', 1, ['---', 'objective: 01-hello-cli', 'status: planned', '---', '', 'No title heading here.', ''].join('\n'));
    const issues = objectiveIssues();
    assert.equal(issues.length, 1, `one objective issue, got ${JSON.stringify(issues.map((i) => i.title))}`);
    assert.equal(issues[0].title, '[Objective 1] hello-cli');
  });
});

describe('55-04 store objective issue title: the ROADMAP name still wins', () => {
  useEmptyStoreProject({ roadmap: `${GENERATED_ROADMAP}\n### Objective 1: Greeting tool\n**Goal:** Say hello\n` });

  test('2. a ROADMAP entry `### Objective 1: Greeting tool` names the issue, not the OBJECTIVE.md heading or the slug', () => {
    if (S.skipped) return;
    putObjective('01-hello-cli', 1, ['---', 'objective: 01-hello-cli', 'status: planned', '---', '', '# Objective 1: Hello CLI', '', '**Goal:** Say hello', ''].join('\n'));
    const issues = objectiveIssues();
    assert.equal(issues.length, 1, `one objective issue, got ${JSON.stringify(issues.map((i) => i.title))}`);
    assert.equal(issues[0].title, '[Objective 1] Greeting tool');
  });
});

'use strict';

/**
 * planning-paths.cjs — the total classifier of `.planning/` paths (objective 48, D-02 and U-1).
 *
 * Every path under `.planning/` is exactly one of four classes:
 *
 *   tracked-config  config.json, STACK.md. Tracked in git in both modes (U-1: the only two files store mode keeps tracked).
 *   cache           Verb-owned documents. Store mode: GitHub is the source of truth, the file is a gitignored cache, and the
 *                   edit gate denies direct writes, naming the verb that owns the file.
 *   generated       ROADMAP.md, STATE.md, MILESTONES.md. Store mode: a view regenerated by `df-tools gh pull --all`.
 *   runtime         Everything else, including anything unrecognised. Never gated; gitignored in store mode.
 *
 * In `local` mode (planning-mode.cjs, D-01) none of this changes behaviour: every file stays tracked and the gate's cache
 * deny is inactive. The classes only bite in `store` mode.
 *
 * Unknown paths are runtime on purpose: classifying one as cache would make the gate deny a file no verb can write.
 *
 * Hook-safe: requires only fs and path, never spawns anything. The objective-dir regexes copy the shape of
 * gh-hierarchy.cjs TRD_FILE_RE and gh-cache.cjs OWNED_OBJECTIVE_FILE_RE rather than requiring those modules.
 */

const fs = require('fs');
const path = require('path');

const CLASSES = Object.freeze(['tracked-config', 'cache', 'generated', 'runtime']);

/** U-1: the only `.planning/` files store mode keeps tracked. */
const TRACKED_CONFIG = Object.freeze(['config.json', 'STACK.md']);

const RUNTIME_FILES = new Set(['state.json', 'STATE_ARCHIVE.md', 'SESSION_PICKUP.md']);
const RUNTIME_TREES = new Set(['evidence', 'workstreams']);
const GENERATED_FILES = new Set(['ROADMAP.md', 'STATE.md', 'MILESTONES.md']);
const TOP_LEVEL_DOCS = new Set(['PROJECT.md', 'REQUIREMENTS.md']);
const FLAT_DOC_DIRS = new Set(['codebase', 'adr', 'retros', 'research', 'milestones']);
const TODO_STATES = { pending: 'open', completed: 'closed', done: 'closed' }; // done/ is the legacy completed dir

// Objective-dir file shapes. The optional `<prefix>-` matches gh-cache OWNED_OBJECTIVE_FILE_RE, so every file 47 owns
// (including a bare CONTEXT.md / RESEARCH.md, which gh-wiki maps to a page) stays cache.
const OBJ_TRD_RE = /^(?:.+-)?TRD\.md$/;
const OBJ_SUMMARY_RE = /^(?:.+-)?SUMMARY\.md$/;
const OBJ_VERIFICATION_RE = /^(?:.+-)?VERIFICATION\.md$/;
const OBJ_OWNED_DOC_RE = /^(?:.+-)?(?:CONTEXT|RESEARCH)\.md$/;
// Any other `<prefix>-<SUFFIX>.md` (UAT, EVIDENCE, ROLLOUT, DISCOVERY, ...). The prefix is required here.
const OBJ_DOC_RE = /^.+-([A-Z][A-Z0-9_]*)\.md$/;
// Legacy suffixes no verb writes: an old `*-JOB.md` is runtime.
const OBJ_DOC_EXCLUDED_SUFFIXES = new Set(['JOB']);

// Argument extraction for hints. Objective id from the dir (`48-slug` -> 48, `2.1-slug` -> 2.1); TRD id from the
// file name, the prefix group of gh-hierarchy TRD_FILE_RE (`48-01-slug-SUMMARY.md` -> 48-01).
const OBJECTIVE_ID_RE = /^(\d+(?:\.\d+)?)(?:-|$)/;
const TRD_ID_RE = /^(\d+(?:\.\d+)?-\d+)(?:-|$)/;

const QUICK_DIR_RE = /^(\d+)-.+$/;
const QUICK_FILE_RE = /^(\d+)-(JOB|SUMMARY)\.md$/;

// The stem half of 48-02's ENTITY_ID_RE (`^(todo|debug)-([a-z0-9][a-z0-9._-]{0,99})$`). A stem it refuses keeps its
// class (the verb still owns the location) but has no entity id.
const ENTITY_STEM_RE = /^[a-z0-9][a-z0-9._-]{0,99}$/;

const isMd = (name) => name.endsWith('.md');
const stemOf = (name) => name.slice(0, -'.md'.length);

function objectiveArg(dir) {
  const m = OBJECTIVE_ID_RE.exec(dir);
  return m ? m[1] : null;
}

function trdArg(file) {
  const m = TRD_ID_RE.exec(file);
  return m ? m[1] : null;
}

function stemEntity(role, stem, state) {
  const lowered = stem.toLowerCase();
  return ENTITY_STEM_RE.test(lowered) ? { role, id: `${role}-${lowered}`, state } : null;
}

/** `{dir, file}` when `seg` is `objectives/<dir>/<file>` and `re` matches the file; else null. */
function objectiveFile(seg, re) {
  if (seg.length !== 3 || seg[0] !== 'objectives' || !re.test(seg[2])) return null;
  return { dir: seg[1], file: seg[2] };
}

const docPutHint = (rel) => `\`df-tools doc put ${rel} --from <draft>\``;

/**
 * THE class table, in order; first match wins. Each rule: `test(rel, seg) -> match | null`, its class and verb,
 * `hint(match, rel)` for cache/generated, and `entity(match)` for entity paths.
 */
const RULES = [
  {
    name: 'tracked-config',
    class: 'tracked-config',
    verb: null,
    test: (rel) => (TRACKED_CONFIG.includes(rel) ? {} : null),
  },
  {
    // A dot-prefixed first segment is runtime (.skill-active, .trd-progress/...). A dot segment deeper down is runtime
    // too: no verb writes a wiki clone's .git/ or an editor swap file.
    name: 'dot-segment',
    class: 'runtime',
    verb: null,
    test: (rel, seg) => (seg.some((s) => s.startsWith('.')) ? {} : null),
  },
  {
    name: 'runtime-named',
    class: 'runtime',
    verb: null,
    test: (rel, seg) => (RUNTIME_FILES.has(rel) || RUNTIME_TREES.has(seg[0]) ? {} : null),
  },
  {
    name: 'generated',
    class: 'generated',
    verb: 'gh pull --all',
    test: (rel) => (GENERATED_FILES.has(rel) ? {} : null),
    hint: () => 'generated view; regenerate with `df-tools gh pull --all`',
  },
  {
    name: 'objective-trd',
    class: 'cache',
    verb: 'plan put-trd',
    test: (rel, seg) => objectiveFile(seg, OBJ_TRD_RE),
    hint: (m) => `\`df-tools plan put-trd ${objectiveArg(m.dir) || '<objective>'} ${m.file} --from <draft>\``,
  },
  {
    name: 'objective',
    class: 'cache',
    verb: 'objective put',
    test: (rel, seg) => objectiveFile(seg, /^OBJECTIVE\.md$/),
    hint: (m) => {
      const id = objectiveArg(m.dir) || '<id>';
      return `\`df-tools objective put ${id} --from <draft>\` or \`objective set-status ${id} <status>\``;
    },
  },
  {
    name: 'objective-summary',
    class: 'cache',
    verb: 'summary post',
    test: (rel, seg) => objectiveFile(seg, OBJ_SUMMARY_RE),
    hint: (m) => `\`df-tools summary post ${trdArg(m.file) || '<trd>'} --from <draft>\``,
  },
  {
    name: 'objective-verification',
    class: 'cache',
    verb: 'verification post',
    test: (rel, seg) => objectiveFile(seg, OBJ_VERIFICATION_RE),
    hint: (m) => `\`df-tools verification post ${objectiveArg(m.dir) || '<objective>'} --from <draft>\``,
  },
  {
    name: 'objective-doc',
    class: 'cache',
    verb: 'doc put',
    test: (rel, seg) => {
      if (objectiveFile(seg, OBJ_OWNED_DOC_RE)) return {};
      const m = objectiveFile(seg, OBJ_DOC_RE);
      return m && !OBJ_DOC_EXCLUDED_SUFFIXES.has(OBJ_DOC_RE.exec(m.file)[1]) ? m : null;
    },
    hint: (m, rel) => docPutHint(rel),
  },
  {
    name: 'doc',
    class: 'cache',
    verb: 'doc put',
    test: (rel, seg) => {
      if (TOP_LEVEL_DOCS.has(rel)) return {};
      if (seg.length === 2 && FLAT_DOC_DIRS.has(seg[0]) && isMd(seg[1])) return {};
      if (seg.length >= 2 && seg[0] === 'wiki') return {};
      return null;
    },
    hint: (m, rel) => docPutHint(rel),
  },
  {
    name: 'todo',
    class: 'cache',
    verb: 'todo add',
    test: (rel, seg) => {
      if (seg.length !== 3 || seg[0] !== 'todos' || !Object.hasOwn(TODO_STATES, seg[1]) || !isMd(seg[2])) return null;
      return { stem: stemOf(seg[2]), state: TODO_STATES[seg[1]] };
    },
    hint: (m) => `\`df-tools todo add --from <draft>\` / \`todo complete ${m.stem}\``,
    entity: (m) => stemEntity('todo', m.stem, m.state),
  },
  {
    name: 'debug',
    class: 'cache',
    verb: 'debug put',
    test: (rel, seg) => {
      if (seg[0] !== 'debug') return null;
      if (seg.length === 2 && isMd(seg[1])) return { stem: stemOf(seg[1]), state: 'open' };
      if (seg.length === 3 && seg[1] === 'resolved' && isMd(seg[2])) return { stem: stemOf(seg[2]), state: 'closed' };
      return null;
    },
    hint: (m) => `\`df-tools debug put ${m.stem} --from <draft>\` / \`debug resolve ${m.stem}\``,
    entity: (m) => stemEntity('debug', m.stem, m.state),
  },
  {
    name: 'quick',
    class: 'cache',
    verb: 'quick put',
    test: (rel, seg) => {
      if (seg.length !== 3 || seg[0] !== 'quick') return null;
      const dir = QUICK_DIR_RE.exec(seg[1]);
      const file = QUICK_FILE_RE.exec(seg[2]);
      if (!dir || !file || dir[1] !== file[1]) return null;
      return { n: file[1], part: file[2] === 'JOB' ? 'job' : 'summary' };
    },
    hint: (m) => `\`df-tools quick put ${m.n} --from <draft>\` / \`quick summary ${m.n} --from <draft>\``,
    entity: (m) => ({ role: 'quick', id: `quick-${m.n}`, part: m.part }),
  },
  {
    name: 'decision',
    class: 'cache',
    verb: 'decision open',
    test: (rel, seg) => (seg.length >= 2 && seg[0] === 'decisions' ? {} : null),
    hint: () => '`df-tools decision open <trd> --question <text>` / `decision answer <id> --from <draft>`',
  },
];

/** Every verb the class table names, deduplicated, in table order. 48-15 asserts each one exists in the df-tools dispatch. */
const VERB_TABLE = Object.freeze([...new Set(RULES.map((r) => r.verb).filter(Boolean))]);

/** The rel's segments; throws TypeError for anything that is not a safe POSIX path relative to `.planning/`. */
function segmentsOf(rel) {
  if (typeof rel !== 'string') throw new TypeError(`planning path must be a string, got ${rel === null ? 'null' : typeof rel}`);
  if (rel === '') throw new TypeError('planning path is empty');
  if (rel.includes('\0')) throw new TypeError('planning path contains NUL');
  if (rel.includes('\\')) throw new TypeError(`planning path must use "/" separators: ${rel}`);
  if (rel.startsWith('/') || path.isAbsolute(rel) || /^[A-Za-z]:/.test(rel)) {
    throw new TypeError(`planning path must be relative to .planning/: ${rel}`);
  }
  const seg = rel.split('/');
  for (const s of seg) {
    if (s === '' || s === '.' || s === '..') throw new TypeError(`unsafe planning path: ${rel}`);
  }
  return seg;
}

/**
 * classify(rel) -> `{class, verb, hint, entity}` for a POSIX path relative to `.planning/` (no leading `./`).
 * Total: an unrecognised path is `runtime`. `verb`/`hint` are set for cache and generated paths, null otherwise; `entity`
 * is `{role:'todo'|'debug', id, state}` or `{role:'quick', id, part}` for entity paths, null otherwise.
 * Throws TypeError for an unsafe rel (`..`, absolute, NUL, backslash, empty segments).
 */
function classify(rel) {
  const seg = segmentsOf(rel);
  for (const rule of RULES) {
    const m = rule.test(rel, seg);
    if (!m) continue;
    return {
      class: rule.class,
      verb: rule.verb,
      hint: rule.hint ? rule.hint(m, rel) : null,
      entity: rule.entity ? rule.entity(m) : null,
    };
  }
  return { class: 'runtime', verb: null, hint: null, entity: null };
}

/** realpath of the deepest existing ancestor of `p`, with the non-existent remainder re-appended. */
function realDeep(p) {
  const resolved = path.resolve(p);
  let cur = resolved;
  const rest = [];
  for (;;) {
    try {
      return path.join(fs.realpathSync(cur), ...rest);
    } catch {
      const parent = path.dirname(cur);
      if (parent === cur) return resolved;
      rest.unshift(path.basename(cur));
      cur = parent;
    }
  }
}

/**
 * The POSIX path of `abs` relative to `planningDir`, or null when `abs` is not strictly inside it. Both sides go through
 * the realpath of their deepest existing ancestor, so a symlinked parent (macOS `/var` vs `/private/var`) and a file that
 * does not exist yet both resolve.
 */
function relToPlanning(abs, planningDir) {
  if (typeof abs !== 'string' || abs === '' || typeof planningDir !== 'string' || planningDir === '') return null;
  const rel = path.relative(realDeep(planningDir), realDeep(abs));
  if (rel === '' || path.isAbsolute(rel) || rel === '..' || rel.startsWith(`..${path.sep}`)) return null;
  return rel.split(path.sep).join('/');
}

/** U-1: the store-mode `.gitignore` lines, a fresh array each call. */
function gitignoreLines() {
  return ['.planning/*', ...TRACKED_CONFIG.map((rel) => `!.planning/${rel}`)];
}

/**
 * Every file under `planningDir`, grouped by class, each list sorted. `.git` directories (the wiki clone's) are not walked.
 * A name classify refuses (a backslash in a POSIX file name) is listed as runtime, so every file lands in exactly one list.
 * A missing dir yields four empty lists.
 */
function listByClass(planningDir) {
  const out = { 'tracked-config': [], cache: [], generated: [], runtime: [] };
  const walk = (dirAbs, parts) => {
    let entries;
    try {
      entries = fs.readdirSync(dirAbs, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      if (e.isDirectory()) {
        if (e.name !== '.git') walk(path.join(dirAbs, e.name), [...parts, e.name]);
        continue;
      }
      if (!e.isFile() && !e.isSymbolicLink()) continue;
      const rel = [...parts, e.name].join('/');
      let cls;
      try {
        cls = classify(rel).class;
      } catch {
        cls = 'runtime';
      }
      out[cls].push(rel);
    }
  };
  if (typeof planningDir === 'string' && planningDir !== '') walk(planningDir, []);
  for (const cls of CLASSES) out[cls].sort();
  return out;
}

module.exports = {
  CLASSES,
  TRACKED_CONFIG,
  VERB_TABLE,
  classify,
  relToPlanning,
  gitignoreLines,
  listByClass,
};

/**
 * makeFakeHome({ legacy, claudeMd }) -> absolute fake home directory
 *
 * Always creates `<home>/.claude/`. `legacy: true` adds the v1 global install leftovers
 * (`.claude/skills/df-plan/SKILL.md`, `.claude/agents/df-planner.md`, `.claude/devflow/VERSION`
 * = "1.20.4") plus a NON-legacy sibling `.claude/skills/keep-me/SKILL.md` that must never move.
 * `claudeMd` (string) is written verbatim to `.claude/CLAUDE.md`.
 */
function makeFakeHome({ legacy = false, claudeMd = null } = {}) {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'df-upgrade-home-'));
  fs.mkdirSync(path.join(home, '.claude'), { recursive: true });

  if (legacy) {
    writeRel(home, '.claude/skills/df-plan/SKILL.md',
      '---\nname: df-plan\ndescription: DevFlow v1 plan command (legacy global install)\n---\n\nLegacy v1 skill body.\n');
    writeRel(home, '.claude/agents/df-planner.md',
      '---\nname: df-planner\ndescription: DevFlow v1 planner agent (legacy global install)\n---\n\nLegacy v1 agent body.\n');
    writeRel(home, '.claude/devflow/VERSION', '1.20.4');
    writeRel(home, '.claude/skills/keep-me/SKILL.md',
      '---\nname: keep-me\ndescription: A user skill that is not DevFlow and must never move\n---\n\nUser skill body.\n');
  }

  if (claudeMd !== null) {
    writeRel(home, '.claude/CLAUDE.md', claudeMd);
  }

  return home;
}

/**
 * makeV1Project(opts) -> absolute project root shaped like a DevFlow v1.x project.
 *
 *   flatConfig         true  → flat v1 config.json keys; false → the nested template shape
 *   jobFiles           true  → NN-NN-JOB.md plan files; false → NN-NN-TRD.md
 *   stateJson          false → no .planning/state.json; true → seeded state.json
 *   missingObjectiveMd true  → objectives/02-beta has no OBJECTIVE.md
 *   projectKind        null  → PROJECT.md frontmatter has no `kind`; a string adds `kind: <it>`
 *   claudeMdBlock      'legacy' → CLAUDE.md with the unversioned DEVFLOW block between user text
 *                      'none'   → CLAUDE.md with the same user text and no block
 *                      null     → no CLAUDE.md
 */
function makeV1Project({
  flatConfig = true,
  jobFiles = true,
  stateJson = false,
  missingObjectiveMd = true,
  projectKind = null,
  claudeMdBlock = 'legacy',
} = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'df-upgrade-project-'));
  const plan = jobFiles ? 'JOB' : 'TRD';

  writeRel(root, '.planning/PROJECT.md', projectMd(projectKind));
  writeRel(root, '.planning/ROADMAP.md', ROADMAP_MD);
  writeRel(root, '.planning/STATE.md', STATE_MD);
  writeJson(root, '.planning/config.json', flatConfig ? { ...V1_FLAT_CONFIG } : nestedTemplateConfig());
  if (stateJson) writeJson(root, '.planning/state.json', STATE_JSON);

  writeRel(root, '.planning/objectives/01-alpha/OBJECTIVE.md', objectiveMd('01-alpha', 'Alpha', 'Alpha goal'));
  writeRel(root, `.planning/objectives/01-alpha/01-01-${plan}.md`, planMd('01-alpha', '01', plan, 'Alpha first job'));
  writeRel(root, '.planning/objectives/01-alpha/01-01-SUMMARY.md', SUMMARY_MD);
  writeRel(root, `.planning/objectives/02-beta/02-01-${plan}.md`, planMd('02-beta', '01', plan, 'Beta first job'));
  if (!missingObjectiveMd) {
    writeRel(root, '.planning/objectives/02-beta/OBJECTIVE.md', objectiveMd('02-beta', 'Beta', 'Beta goal'));
  }

  if (claudeMdBlock === 'legacy') {
    writeRel(root, 'CLAUDE.md', CLAUDE_MD_BEFORE + LEGACY_CLAUDE_MD_BLOCK + CLAUDE_MD_AFTER);
  } else if (claudeMdBlock === 'none') {
    writeRel(root, 'CLAUDE.md', CLAUDE_MD_BEFORE + '## After\n\nkeep me too\n');
  } else if (claudeMdBlock !== null) {
    throw new Error(`makeV1Project: claudeMdBlock must be 'legacy', 'none' or null (got ${JSON.stringify(claudeMdBlock)})`);
  }

  return root;
}

/**
 * makeStampedProject(version, { migrations_applied }) -> absolute project root
 *
 * A current-shape project with nothing pending: nested config.json carrying a `devflow` stamp,
 * TRD plan files, state.json, an OBJECTIVE.md in every objective dir, PROJECT.md with `kind`,
 * and a CLAUDE.md without any DEVFLOW block.
 */
function makeStampedProject(version, { migrations_applied = [] } = {}) {
  const root = makeV1Project({
    flatConfig: false,
    jobFiles: false,
    stateJson: true,
    missingObjectiveMd: false,
    projectKind: 'app',
    claudeMdBlock: 'none',
  });
  const configPath = path.join(root, '.planning', 'config.json');
  const config = JSON.parse(fs.readFileSync(configPath, 'utf-8'));
  config.devflow = {
    version,
    migrations_applied: [...migrations_applied],
    upgraded_at: FIXTURE_STAMP_TIME,
  };
  fs.writeFileSync(configPath, JSON.stringify(config, null, 2) + '\n', 'utf-8');
  return root;
}

// Env vars that would redirect a git command at some OTHER repository (e.g. when the suite runs
// inside a git hook of this repo). Stripped so fixture git calls can only ever touch the fixture.
const GIT_REDIRECT_VARS = [
  'GIT_DIR', 'GIT_WORK_TREE', 'GIT_INDEX_FILE', 'GIT_OBJECT_DIRECTORY',
  'GIT_ALTERNATE_OBJECT_DIRECTORIES', 'GIT_COMMON_DIR', 'GIT_PREFIX', 'GIT_NAMESPACE',
];

/**
 * gitEnv(home) -> env for every fixture git call: fake HOME, fake XDG config, no system config.
 */
function gitEnv(home) {
  const env = {
    ...process.env,
    HOME: home,
    XDG_CONFIG_HOME: path.join(home, '.config'),
    GIT_CONFIG_NOSYSTEM: '1',
  };
  for (const key of GIT_REDIRECT_VARS) delete env[key];
  return env;
}

/**
 * initGitFixture(root, home) -> void
 *
 * `git init -b main`, LOCAL identity + commit.gpgsign=false + tag.gpgsign=false (on the fixture
 * repo only — never global), then `add -A` and one `init` commit.
 */
function initGitFixture(root, home) {
  const git = (...args) => execFileSync('git', ['-C', root, ...args], {
    env: gitEnv(home),
    stdio: ['ignore', 'pipe', 'pipe'],
    encoding: 'utf-8',
  });
  git('init', '-q', '-b', 'main');
  git('config', 'user.name', 'DevFlow Fixture');
  git('config', 'user.email', 'fixture@devflow.invalid');
  git('config', 'commit.gpgsign', 'false');
  git('config', 'tag.gpgsign', 'false');
  git('add', '-A');
  git('commit', '-q', '-m', 'init');
}

// Hand-written runtime-state bodies (TRD 44-06). Shaped like what guard-no-progress.js and
// awareness-cache-populate.js write, but literal and tiny — the migration never parses them.
const RUNTIME_STATE_CONTENT = {
  '.planning/.progress-guard.json': '{\n  "last": "Bash:9f2c1e",\n  "count": 1\n}\n',
  '.planning/.awareness-cache.json': '{\n  "generated_at": "2026-01-01T00:00:00.000Z",\n  "branches": []\n}\n',
};

/**
 * makeTrackedRuntimeStateProject(opts) -> { root, home }  (TRD 44-06, migration 0008)
 *
 * A stamped project (makeStampedProject) turned into a git fixture with DevFlow runtime-state
 * files in a chosen git state:
 *
 *   tracked           paths written BEFORE the init commit, so they are committed (tracked)
 *   untrackedPresent  paths written AFTER every commit — on disk, never added
 *   gitignore         null → no .gitignore; a string → written verbatim as `.gitignore` and
 *                     committed in a SECOND commit, after `tracked` is already in HEAD. That is the
 *                     real-world shape: a file tracked first and ignored later stays tracked.
 *   version           the devflow stamp version (default '2.0.0', i.e. behind any bundled version)
 *   home              an existing fake home; default: a fresh makeFakeHome()
 *
 * Every git call runs through initGitFixture/gitEnv(home) — local identity, no signing.
 */
function makeTrackedRuntimeStateProject({
  tracked = ['.planning/.progress-guard.json'],
  untrackedPresent = [],
  gitignore = null,
  version = '2.0.0',
  home = null,
} = {}) {
  const fakeHome = home || makeFakeHome();
  const root = makeStampedProject(version);
  const contentFor = (rel) => RUNTIME_STATE_CONTENT[rel] || '{\n  "fixture": true\n}\n';

  for (const rel of tracked) writeRel(root, rel, contentFor(rel));
  initGitFixture(root, fakeHome);

  if (gitignore !== null) {
    writeRel(root, '.gitignore', gitignore);
    const git = (...args) => execFileSync('git', ['-C', root, ...args], {
      env: gitEnv(fakeHome),
      stdio: ['ignore', 'pipe', 'pipe'],
      encoding: 'utf-8',
    });
    git('add', '--', '.gitignore');
    git('commit', '-q', '-m', 'add .gitignore');
  }

  for (const rel of untrackedPresent) writeRel(root, rel, contentFor(rel));
  return { root, home: fakeHome };
}

/**
 * migrationSource({ id, title, since, safety, detect, apply }) -> CommonJS source string
 *
 * `detect` and `apply` are FUNCTION-BODY strings (the body of `detect(ctx) { ... }`). Any field
 * passed as `undefined` is omitted from the export, so contract-violation fixtures can drop one.
 * `fs` and `path` are in scope for the bodies.
 */
function migrationSource({ id, title = 't', since = '2.11.0', safety = 'auto', detect, apply } = {}) {
  const lines = ["'use strict';", "const fs = require('fs');", "const path = require('path');", 'module.exports = {'];
  if (id !== undefined) lines.push(`  id: ${JSON.stringify(id)},`);
  if (title !== undefined) lines.push(`  title: ${JSON.stringify(title)},`);
  if (since !== undefined) lines.push(`  since: ${JSON.stringify(since)},`);
  if (safety !== undefined) lines.push(`  safety: ${JSON.stringify(safety)},`);
  if (detect !== undefined) lines.push(`  detect(ctx) {\n${detect}\n  },`);
  if (apply !== undefined) lines.push(`  apply(ctx) {\n${apply}\n  },`);
  lines.push('};');
  return lines.join('\n') + '\n';
}

/**
 * makeRegistryDir({ [filename]: source }) -> absolute registry dir
 */
function makeRegistryDir(files = {}) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'df-upgrade-registry-'));
  for (const [name, source] of Object.entries(files)) {
    fs.writeFileSync(path.join(dir, name), source, 'utf-8');
  }
  return dir;
}

/**
 * snapshot(root) -> { [relPosixPath]: sha1 } of every file under root, skipping `.git/`.
 * Symlinks are recorded by target (`symlink:<target>`), never followed.
 */
function snapshot(root) {
  const out = {};
  const walk = (dir, rel) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.name === '.git') continue;
      const abs = path.join(dir, entry.name);
      const relPath = rel ? `${rel}/${entry.name}` : entry.name;
      if (entry.isSymbolicLink()) {
        out[relPath] = crypto.createHash('sha1').update('symlink:' + fs.readlinkSync(abs)).digest('hex');
      } else if (entry.isDirectory()) {
        walk(abs, relPath);
      } else if (entry.isFile()) {
        out[relPath] = crypto.createHash('sha1').update(fs.readFileSync(abs)).digest('hex');
      }
    }
  };
  walk(root, '');
  return out;
}

/**
 * diffSnapshots(a, b) -> sorted relative paths that were added, removed or changed.
 */
function diffSnapshots(a, b) {
  const keys = new Set([...Object.keys(a), ...Object.keys(b)]);
  return [...keys].filter((k) => a[k] !== b[k]).sort();
}

